  function make(lang) {
    const d = D[lang] || D.en;
    return (key, vars) => {
      let s = d[key] != null ? d[key] : (D.en[key] != null ? D.en[key] : key);
      if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ''));
      return s;
    };
  }

  function pickLang(setting, systemLangs) {
    if (setting && setting !== 'auto' && D[setting]) return setting;
    const first = (systemLangs && systemLangs[0]) || 'en';
    return /^ru\b/i.test(first) ? 'ru' : 'en';
  }

  const api = { D, make, pickLang };
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.I18N = api;
