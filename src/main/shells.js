'use strict';
// Available shells, and how to make them report the current directory (OSC 7 / OSC 9;9).
const fs = require('fs');
const path = require('path');
const os = require('os');

function exists(p) {
  try { return fs.statSync(p).isFile(); } catch { return false; }
}

function findGitBash() {
  const candidates = [
    process.env.ProgramFiles && path.join(process.env.ProgramFiles, 'Git', 'bin', 'bash.exe'),
    process.env['ProgramFiles(x86)'] && path.join(process.env['ProgramFiles(x86)'], 'Git', 'bin', 'bash.exe'),
    process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Programs', 'Git', 'bin', 'bash.exe'),
  ].filter(Boolean);
  return candidates.find(exists) || null;
}

function findPwsh() {
  const candidates = [
    process.env.ProgramFiles && path.join(process.env.ProgramFiles, 'PowerShell', '7', 'pwsh.exe'),
    process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Microsoft', 'WindowsApps', 'pwsh.exe'),
  ].filter(Boolean);
  return candidates.find(exists) || null;
}

// bash rc file: emulates a login shell and adds an OSC 7 with the current directory to PROMPT_COMMAND.
function bashInitFile(dataDir) {
  const file = path.join(dataDir, 'bash-init.sh');
  const body = [
    '# Generated by Kolonka. Emulates a login shell and reports the current directory to the terminal.',
    '[ -f /etc/profile ] && . /etc/profile',
    'if [ -f ~/.bash_profile ]; then . ~/.bash_profile',
    'elif [ -f ~/.bash_login ]; then . ~/.bash_login',
    'elif [ -f ~/.profile ]; then . ~/.profile',
    'elif [ -f ~/.bashrc ]; then . ~/.bashrc; fi',
    '__kolonka_osc7() { printf \'\\033]7;file://%s%s\\007\' "${HOSTNAME:-localhost}" "$PWD"; }',
    'case ";${PROMPT_COMMAND};" in *";__kolonka_osc7;"*) ;; *) PROMPT_COMMAND="__kolonka_osc7${PROMPT_COMMAND:+;$PROMPT_COMMAND}";; esac',
    '',
  ].join('\n');
  try {
    if (!exists(file) || fs.readFileSync(file, 'utf8') !== body) fs.writeFileSync(file, body);
  } catch { /* not critical */ }
  return file;
}

const PS_INIT =
  '$__kolonkaPrompt = $function:prompt; ' +
  'function global:prompt { $e = [char]27; $p = $executionContext.SessionState.Path.CurrentLocation.ProviderPath; ' +
  '[Console]::Write("$e]9;9;$p$e\\"); & $__kolonkaPrompt }';

function detectShells(dataDir) {
  const shells = {};
  const bash = findGitBash();
  if (bash) {
    shells.bash = {
      label: 'Git Bash',
      file: bash,
      args: ['--rcfile', bashInitFile(dataDir).replace(/\\/g, '/'), '-i'],
      env: { CHERE_INVOKING: '1', TERM: 'xterm-256color' },
    };
  }
  const pwsh = findPwsh();
  if (pwsh) {
    shells.pwsh = { label: 'PowerShell 7', file: pwsh, args: ['-NoLogo', '-NoExit', '-Command', PS_INIT], env: {} };
  }
  shells.powershell = {
    label: 'Windows PowerShell',
    file: path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'WindowsPowerShell', 'v1.0', 'powershell.exe'),
    args: ['-NoLogo', '-NoExit', '-Command', PS_INIT],
    env: {},
  };
  shells.cmd = {
    label: 'Command Prompt',
    file: process.env.ComSpec || 'cmd.exe',
    args: [],
    env: { PROMPT: '$e]9;9;$P$e\\$P$G' },
  };
  return shells;
}

// Convert an msys path (/c/Users/x) to a Windows one (C:\Users\x).
function msysToWin(p) {
  if (!p) return null;
  const m = /^\/([a-zA-Z])(\/.*)?$/.exec(p);
  if (m) return (m[1].toUpperCase() + ':' + (m[2] || '\\')).replace(/\//g, '\\');
  if (/^[a-zA-Z]:[\\/]/.test(p)) return p.replace(/\//g, '\\');
  return null;
}

function parseOsc7(data) {
  // file://host/path
  const m = /^file:\/\/[^/]*(\/.*)$/.exec(data);
  if (!m) return null;
  let p;
  try { p = decodeURIComponent(m[1]); } catch { p = m[1]; }
  // file:///C:/x → /C:/x
  if (/^\/[a-zA-Z]:\//.test(p)) p = p.slice(1);
  return msysToWin(p);
}

module.exports = { detectShells, parseOsc7, msysToWin, homeDir: os.homedir() };
